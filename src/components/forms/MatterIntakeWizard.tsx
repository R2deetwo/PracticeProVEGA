// LocalStorage frequency helpers — actions the user picks most often float to the top
const FREQ_KEY = 'pp_action_freq';
const getActionFreq = (): Record<string, number> => {
    try { return JSON.parse(localStorage.getItem(FREQ_KEY) || '{}'); } catch { return {}; }
};
export const recordActionUsed = (action: string) => {
    const freq = getActionFreq();
    freq[action] = (freq[action] || 0) + 1;
    localStorage.setItem(FREQ_KEY, JSON.stringify(freq));
};

export const autoFormatSuitTitle = (claimants: LitigationParty[], defendants: LitigationParty[], action?: string) => {
    if (claimants.length === 0 || defendants.length === 0) return '';
    const claimantNames = claimants.map(c => c.name).join(', ');
    const defendantNames = defendants.map(d => d.name).join(', ');
    
    // Determine the connector based on action type
    const roles = action ? PARTY_ROLES[action] || PARTY_ROLES['Generic / Other'] : PARTY_ROLES['Generic / Other'];
    let connector = 'v.';
    if (roles.claimant === 'Applicant' && roles.defendant === 'Respondent') connector = 'v.';
    if (roles.claimant === 'Petitioner' && roles.defendant === 'Respondent') connector = 'v.';
    
    return `${claimantNames} ${connector} ${defendantNames}`;
};

