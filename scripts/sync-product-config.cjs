#!/usr/bin/env node
/**
 * sync-product-config.cjs — per-product APK wrapper swap (Brand Clarity
 * Pass, Phase 2).
 *
 * Same workaround family as sync-admin-config.cjs: Capacitor 8 CLI has no
 * --config flag, so we swap capacitor.config.ts atomically before running
 * `npx cap sync android`. The product variants (Vega / Atrium / Komplete)
 * SHARE the universal applicationId (com.practicepro.app) — a product APK
 * installs/updates over any existing install (installed base, FCM and deep
 * links keep working). Only the wrapper branding differs:
 *
 *   1. capacitor.config.ts          → the product config (appName: "Vega"…)
 *   2. strings.xml app_name /
 *      title_activity_main          → the product display name
 *      (package_name / custom_url_scheme / applicationId stay UNCHANGED)
 *   3. launcher icon set            → android/branding/<product>/res/** is
 *      copied over android/app/src/main/res/** (adaptive foreground vector,
 *      background colour, and legacy mipmap PNGs for API 24–25)
 *
 * The native splash STAYS company-branded on every variant (owner
 * direction: the PracticePro opening is liked as-is; the in-app cinematic
 * splash is what ends on the product mark — SplashScreen.tsx).
 *
 * Swap   :  node scripts/sync-product-config.cjs --product vega [--open]
 * Restore:  automatic on exit (local); in CI the patched files stay in
 *           place for the following Gradle step (same contract as
 *           sync-admin-config.cjs — the runner is ephemeral).
 *
 * Assets are generated by scripts/generate-product-launcher-assets.py
 * (run once, committed) from public/brand/<product>/favicon.svg.
 */

const fs = require('fs');
const path = require('path');
const { execSync } = require('child_process');

const ROOT = path.resolve(__dirname, '..');

const PRODUCTS = {
    vega: { displayName: 'Vega' },
    atrium: { displayName: 'Atrium' },
    komplete: { displayName: 'Komplete' },
};

// ── CLI ───────────────────────────────────────────────────────────────────
const args = process.argv.slice(2);
const productArg = (() => {
    const i = args.indexOf('--product');
    if (i !== -1 && args[i + 1]) return args[i + 1];
    return null;
})();
const openOnly = args.includes('--open');

if (!productArg || !PRODUCTS[productArg]) {
    console.error('[sync-product] FATAL: pass --product <vega|atrium|komplete>');
    process.exit(2);
}
const product = productArg;
const displayName = PRODUCTS[product].displayName;

const MAIN_CONFIG = path.join(ROOT, 'capacitor.config.ts');
const PRODUCT_CONFIG = path.join(ROOT, `capacitor.${product}.config.ts`);
const CONFIG_BACKUP = path.join(ROOT, 'capacitor.config.ts.product-backup');

const RES = path.join(ROOT, 'android', 'app', 'src', 'main', 'res');
const BRANDING_RES = path.join(ROOT, 'android', 'branding', product, 'res');

const STRINGS_XML = path.join(RES, 'values', 'strings.xml');
// NOTE: backups for files inside res/ MUST be stored OUTSIDE res/ — Android's
// resource merger (AAPT) fails on stray files in res/ (same lesson as
// sync-admin-config.cjs).
const BACKUP_DIR = path.join(ROOT, 'android', 'branding', '.backups', product);

const isCI = process.env.CI === 'true' || process.env.GITHUB_ACTIONS === 'true';

function log(msg) { console.log(`[sync-product:${product}] ${msg}`); }
function warn(msg) { console.warn(`[sync-product:${product}] WARN: ${msg}`); }

if (!fs.existsSync(PRODUCT_CONFIG)) {
    console.error(`[sync-product:${product}] FATAL: config not found at ${PRODUCT_CONFIG}`);
    process.exit(2);
}
if (!fs.existsSync(BRANDING_RES)) {
    console.error(`[sync-product:${product}] FATAL: branding assets not found at ${BRANDING_RES}`);
    console.error(`[sync-product:${product}]        run: python3 scripts/generate-product-launcher-assets.py`);
    process.exit(2);
}

// ── Restore machinery ─────────────────────────────────────────────────────
let restored = false;
function backupFile(relFromRoot) {
    const src = path.join(ROOT, relFromRoot);
    if (!fs.existsSync(src)) return null;
    const dst = path.join(BACKUP_DIR, relFromRoot);
    fs.mkdirSync(path.dirname(dst), { recursive: true });
    fs.copyFileSync(src, dst);
    return dst;
}
function restoreFile(relFromRoot) {
    const src = path.join(ROOT, relFromRoot);
    const bak = path.join(BACKUP_DIR, relFromRoot);
    if (fs.existsSync(bak)) {
        fs.copyFileSync(bak, src);
    } else if (fs.existsSync(src)) {
        // File did not exist before the swap (product-added resource) —
        // remove it so the committed default state is exact.
        fs.rmSync(src, { force: true });
    }
}

function restore() {
    if (restored) return;
    restored = true;
    if (isCI) {
        log('Running in CI — leaving patched files in place for the Gradle build.');
        return;
    }
    try {
        // Restore in reverse order of the swap. The icon swap replaced
        // android/app/src/main/res/<relToRes> — restore those DESTINATION
        // paths, not the branding source paths.
        const walkResRel2 = (dir, acc = []) => {
            for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
                const full = path.join(dir, entry.name);
                if (entry.isDirectory()) walkResRel2(full, acc);
                else acc.push(path.relative(BRANDING_RES, full).replace(/\\/g, '/'));
            }
            return acc;
        };
        if (fs.existsSync(BRANDING_RES)) {
            walkResRel2(BRANDING_RES).forEach((relToRes) =>
                restoreFile(`android/app/src/main/res/${relToRes}`)
            );
        }
        restoreFile('android/app/src/main/res/values/strings.xml');
        if (fs.existsSync(CONFIG_BACKUP)) {
            fs.copyFileSync(CONFIG_BACKUP, MAIN_CONFIG);
            fs.rmSync(CONFIG_BACKUP, { force: true });
        }
        fs.rmSync(BACKUP_DIR, { recursive: true, force: true });
        log('Restored the universal (PracticePro) wrapper state.');
    } catch (e) {
        warn(`restore failed: ${e.message}`);
        warn(`Manual restore: git checkout -- capacitor.config.ts android/app/src/main/res`);
    }
}

// Restore on every exit path — the committed state must never be left
// clobbered by an interrupted swap (same contract as sync-admin-config.cjs).
process.on('exit', restore);
process.on('SIGINT', () => { restore(); process.exit(130); });
process.on('uncaughtException', (e) => { restore(); throw e; });

// ── 1. Swap the Capacitor config ──────────────────────────────────────────
fs.copyFileSync(MAIN_CONFIG, CONFIG_BACKUP);
fs.copyFileSync(PRODUCT_CONFIG, MAIN_CONFIG);
log(`Swapped capacitor.config.ts → ${product} variant (appName: "${displayName}")`);

// ── 2. Patch strings.xml (app_name + title_activity_main ONLY) ────────────
// applicationId / package_name / custom_url_scheme are deliberately NOT
// touched — every product APK is an in-place update of com.practicepro.app.
backupFile('android/app/src/main/res/values/strings.xml');
let stringsXml = fs.readFileSync(STRINGS_XML, 'utf8');
stringsXml = stringsXml.replace(
    /(<string name="app_name">)[^<]*(<\/string>)/,
    `$1${displayName}$2`
);
stringsXml = stringsXml.replace(
    /(<string name="title_activity_main">)[^<]*(<\/string>)/,
    `$1${displayName}$2`
);
fs.writeFileSync(STRINGS_XML, stringsXml);
log(`Patched strings.xml: app_name → "${displayName}"`);

// ── 3. Swap the launcher icon set ─────────────────────────────────────────
// Every file under android/branding/<product>/res/<subpath> is copied to
// android/app/src/main/res/<subpath> (same resource NAMES — the manifest
// needs no change; the swap replaces the company set with the product set).
const walkResRel = (dir, acc = []) => {
    for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
        const full = path.join(dir, entry.name);
        if (entry.isDirectory()) walkResRel(full, acc);
        else acc.push(path.relative(BRANDING_RES, full).replace(/\\/g, '/'));
    }
    return acc;
};
const resFiles = walkResRel(BRANDING_RES);
for (const relToRes of resFiles) {
    const dstRel = `android/app/src/main/res/${relToRes}`;
    backupFile(dstRel); // backs up the company file being replaced (if present)
    const dst = path.join(ROOT, dstRel);
    fs.mkdirSync(path.dirname(dst), { recursive: true });
    fs.copyFileSync(path.join(BRANDING_RES, relToRes), dst);
}
log(`Swapped ${resFiles.length} launcher icon resources from android/branding/${product}/res/`);

// ── 4. Run cap sync (or open) ─────────────────────────────────────────────
try {
    if (openOnly) {
        execSync('npx cap open android', { stdio: 'inherit', cwd: ROOT });
    } else {
        execSync('npx cap sync android', { stdio: 'inherit', cwd: ROOT });
    }
} catch (e) {
    warn('cap sync failed — restoring and exiting non-zero.');
    process.exitCode = 1;
    restore();
    process.exit(1);
}

if (!isCI) {
    log('Done. Local state restored to the universal wrapper.');
    log('In CI, the patched state is kept for the Gradle build.');
} else {
    log('Done. Patched state left in place for the Gradle build.');
}
log(`Expected artifact: ${product}-v<version>-<channel>.apk (rename happens in the workflow/named by the pack step).`);
