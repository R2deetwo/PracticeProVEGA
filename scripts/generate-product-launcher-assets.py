MIPMAP_DENSITIES = {
    "mdpi": 48,
    "hdpi": 72,
    "xhdpi": 96,
    "xxhdpi": 144,
    "xxxhdpi": 192,
}

VECTOR_WRAPPER = """<?xml version="1.0" encoding="utf-8"?>
<!--
  {title} launcher icon foreground — generated by
  scripts/generate-product-launcher-assets.py (Brand Clarity Pass, Phase 2).
  Do not edit by hand; regenerate instead. Same construction as
  public/brand/{key}/favicon.svg (flat register at icon scale).
-->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
{content}
</vector>
"""

COLOR_WRAPPER = """<?xml version="1.0" encoding="utf-8"?>
<!-- {title} adaptive-icon background — generated by
     scripts/generate-product-launcher-assets.py. Do not edit by hand. -->
<resources>
    <color name="ic_launcher_background">{color}</color>
</resources>
"""

TITLES = {
    "vega": "PracticePro Vega (the Seal)",
    "atrium": "PracticePro Atrium (the Stepped Stack)",
    "komplete": "PracticePro Komplete (the Twin Coins)",
}


def write(path, content):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        f.write(content)
    print(f"  wrote {os.path.relpath(path, ROOT)}")


def render_pngs(key, product_dir):
    """Render the full-tile favicon at every mipmap density + a circle-
    masked round variant (legacy API 24-25 launchers)."""
    svg_path = os.path.join(ROOT, "public", "brand", key, "favicon.svg")
    if not os.path.exists(svg_path):
        print(f"  FATAL: {svg_path} not found", file=sys.stderr)
        sys.exit(2)
    with open(svg_path, "rb") as f:
        svg_bytes = f.read()

    for density, size in MIPMAP_DENSITIES.items():
        square_png = os.path.join(
            product_dir, "res", f"mipmap-{density}", "ic_launcher.png"
        )
        os.makedirs(os.path.dirname(square_png), exist_ok=True)
        cairosvg.svg2png(bytestring=svg_bytes, write_to=square_png,
                         output_width=size, output_height=size)
        print(f"  wrote {os.path.relpath(square_png, ROOT)}")

        # Round variant: circle-mask the tile (launchers that honour
        # ic_launcher_round get a true circle, not a cropped square).
        img = Image.open(square_png).convert("RGBA")
        mask = Image.new("L", (size, size), 0)
        ImageDraw.Draw(mask).ellipse((0, 0, size - 1, size - 1), fill=255)
        img.putalpha(mask)
        round_png = os.path.join(
            product_dir, "res", f"mipmap-{density}", "ic_launcher_round.png"
        )
        img.save(round_png)
        print(f"  wrote {os.path.relpath(round_png, ROOT)}")


def main():
    print("Generating per-product launcher assets (android/branding/)…")
    for key, spec in PRODUCTS.items():
        print(f"[{key}]")
        product_dir = os.path.join(BRAND, key)
        title = TITLES[key]

        # 1. Adaptive foreground vectors (both drawable buckets).
        vec = VECTOR_WRAPPER.format(title=title, key=key,
                                    content=spec["foreground_xml"])
        write(os.path.join(product_dir, "res", "drawable",
                           "ic_launcher_foreground.xml"), vec)
        write(os.path.join(product_dir, "res", "drawable-v24",
                           "ic_launcher_foreground.xml"), vec)

        # 2. Adaptive background colour.
        write(os.path.join(product_dir, "res", "values",
                           "ic_launcher_background.xml"),
              COLOR_WRAPPER.format(title=title, color=spec["background"]))

        # 3. Legacy mipmap PNGs.
        render_pngs(key, product_dir)

    print("Done. sync-product-config.cjs swaps these over res/ at build time.")


if __name__ == "__main__":
    main()
