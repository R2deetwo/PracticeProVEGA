#!/usr/bin/env python3
"""
generate-product-launcher-assets.py — per-product Android launcher icon sets
(Brand Clarity Pass, Phase 2).

Generates android/branding/<product>/res/** for vega / atrium / komplete:

  1. ADAPTIVE ICON FOREGROUND (API 26+) — hand-expressed Android vector
     drawables (108dp viewport, content scaled 1.5 + translated 18 so the
     mark sits inside the 66dp safe zone). Flat colours from the product
     favicon — gradients are approximated by their lit corner (they read
     as depth cues, not identity, at icon scale).
       drawable/ic_launcher_foreground.xml      (drawable/ bucket)
       drawable-v24/ic_launcher_foreground.xml  (API 24+ bucket, same file)

  2. ADAPTIVE ICON BACKGROUND — values/ic_launcher_background.xml, the
     product tile colour (the tile the favicon already carries).

  3. LEGACY LAUNCHER PNGs (API 24-25) — public/brand/<product>/favicon.svg
     rendered via cairosvg at the five mipmap densities, square + round.

The assets are COMMITTED (regeneration is one command, provenance is this
script). sync-product-config.cjs copies them over android/app/src/main/res/
at build time; the company set stays the committed default.

Run:  python3 scripts/generate-product-launcher-assets.py
Deps: pip install cairosvg  ( Pillow for the round mask )
"""

import os
import sys

